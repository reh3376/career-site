// The decision test (docs/fsd-decision-test.md). A fifteen-minute
// instrument measuring what happens to a person's accuracy and to their
// confidence as attention is loaded.
//
// Public, because anonymous reach is the point: participants are
// recruited volunteers rather than members.
//
// THE ANSWER KEY NEVER CROSSES THIS BOUNDARY. A question carries its
// prompt and its options and nothing else. Grading happens in the api,
// the client posts a choice and receives an acknowledgement rather than
// a verdict, and the running score is never sent. That is what makes
// "no correctness feedback during the test" a property of the system
// instead of a UI convention, and it matters because confidence is a
// dependent variable: a participant who learns they were wrong stops
// giving an uncontaminated rating.

