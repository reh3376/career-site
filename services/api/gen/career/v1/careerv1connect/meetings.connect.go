// Meeting scheduling against Roger's own calendar. Signed-in members
// see the slots he has opened, pick a length, and book one; the
// application claims the interval in its own database first and only
// then writes the event, because the database is the thing that can
// settle a race between two members submitting the same slot.
//
// Members only, by the owner's decision (2026-09-29): the target is his
// main personal calendar, so an unauthenticated visitor could hold real
// hours on it. His words: "a public facing calendar is asking for
// trouble."
//
// Two rules shape every message here.
//
// Free/busy only, never event contents. The application asks the
// calendar which intervals are taken and nothing else, so a private
// appointment's title never enters this system and cannot leak through
// an availability response.
//
// One zone, stated, never converted. Times are carried as instants and
// rendered in the owner's zone (an IANA name, never a fixed offset,
// because America/New_York is UTC-5 in winter and UTC-4 in summer).
// The zone travels with the response so a page can say which clock it
// is quoting rather than silently using the visitor's.

