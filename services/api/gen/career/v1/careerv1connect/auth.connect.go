// Identity: registration, email verification, password sign-in, password
// reset and credential changes.
//
// **This header described four things that were not true**, and five
// more claims elsewhere in the file were wrong in the same way: Login's
// MFA gate, the `mfa_required` field, MfaEnroll, MfaVerify, ChangeEmail's
// "social-only accounts" and LoginResponse's unverified session. All
// corrected on 2026-10-11 at the end of the work in
// docs/sprint-auth-interceptor.md, because every one of them was the
// kind of claim a security review takes at face value. They are listed
// rather than quietly deleted, so anyone who read the old version can
// see what changed.
//
// Sessions are opaque server-side identifiers delivered in the
// `career_site_session` cookie (HttpOnly; Secure in production;
// SameSite=Lax; 30-day lifetime from SESSION_TTL_HOURS). Clients never
// see or send a token; the browser sends the cookie on every same-origin
// request.
//
//  1. The cookie was named here as `career_session`. It is
//     `career_site_session` (handlers.SessionCookieName).
//
//  2. A "7-day idle timeout" was claimed and is not enforced.
//     `sessions.last_active_at` is bumped on every lookup, but the
//     lookup's only expiry condition is `expires_at > now()`, and
//     nothing sweeps idle rows. The column feeds the activity figures on
//     the admin console and nothing else, so a session is valid for its
//     full 30 days however long it sits unused.
//
//  3. Cross-site request forgery was credited to a required
//     `Connect-Protocol-Version: 1` header, "being a non-simple header".
//     That header is not required: connect-go only enforces it under
//     `connect.WithRequireConnectProtocolHeader()`, which this server
//     does not set, and a `Login` POST carrying only
//     `Content-Type: application/json` is accepted and processed.
//     What does protect these endpoints is `SameSite=Lax` on the cookie,
//     which stops a cross-site POST from carrying it at all. The
//     protection is real; the mechanism named was not. Requiring the
//     header would add a second layer and is worth doing, and it is a
//     behaviour change rather than a comment fix: three deploy scripts
//     call these RPCs with plain curl and would start failing.
//
//  4. Two `GET /api/auth/oauth/{provider}/start` and `/callback` routes
//     were documented for linkedin, github and google, with PKCE, state
//     and account linking by verified email. **No such routes exist.**
//     There is no handler, no provider configuration and no OAuth
//     sign-in code anywhere in the service; the only OAuth here is
//     Google Calendar, for the owner's own calendar. Social sign-in has
//     never been built, so password sign-in is the only way in.
//
// MFA is also absent and intentionally so. `MfaEnroll` and `MfaVerify`
// are declared below and have no handler, the `mfa_fresh` option was
// removed from all 79 methods that carried it on 2026-10-09, and the
// owner decided then not to build a second factor. The first line of
// this comment used to say the service covered "admin MFA".

